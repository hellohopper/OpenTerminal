import { test, expect } from "@playwright/test";
import { signIn } from "./helpers";
test("switches modes without altering desktop panels, remembers simple navigation and saves home choices", async ({ page }, info) => {
  await signIn(page);
  const before = await page.evaluate(() => JSON.parse(localStorage.getItem("openterminal-workspace")!).state.workspaces[0].layout);
  await page.getByLabel("Interface mode", { exact: true }).selectOption("simple");
  await expect(page.getByRole("navigation", { name: "Simple navigation" })).toBeVisible();
  await expect(page.getByRole("navigation", { name: "Widget library", exact: true })).toHaveCount(0);
  await page.getByText("Customize home", { exact: true }).click();
  await page.getByRole("checkbox", { name: "Market briefing", exact: true }).uncheck();
  await page.getByRole("navigation", { name: "Simple navigation" }).getByRole("button", { name: "Watchlist", exact: true }).click();
  await page.getByLabel("Add ticker", { exact: true }).fill("IBM");
  await page.getByRole("button", { name: "Add", exact: true }).click();
  await expect(page.getByRole("button", { name: "Research IBM", exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole("heading", { name: "Watchlist", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Research IBM", exact: true }).click();
  const research = page.getByRole("dialog", { name: "IBM research" });
  await expect(research.getByRole("button", { name: "Financials", exact: true })).toBeVisible();
  await expect(research.getByRole("button", { name: "Timeline", exact: true })).toBeHidden();
  await research.getByText("More research", { exact: true }).click();
  await research.getByRole("button", { name: "Timeline", exact: true }).click();
  await research.getByRole("button", { name: "Close research", exact: true }).click();
  await page.getByRole("navigation", { name: "Simple navigation" }).getByRole("button", { name: "Today", exact: true }).click();
  await expect(page.getByRole("region", { name: "Market briefing", exact: true })).toHaveCount(0);
  await page.screenshot({ path: info.outputPath("simple-desktop.png") });
  await page.getByLabel("Interface mode", { exact: true }).selectOption("professional");
  await expect(page.getByRole("region", { name: "Chart", exact: true })).toBeVisible();
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem("openterminal-workspace")!).state.workspaces[0].layout)).toEqual(before);
});
