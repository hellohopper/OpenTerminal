import { test, expect } from "@playwright/test";
import { signIn, blank } from "./helpers";
test("opens a stock research view, creates a note and a symbol-bound alert", async ({ page }, testInfo) => {
  await signIn(page); await blank(page, "Research workflow");
  await page.getByRole("button", { name: "WATCHLIST", exact: true }).click();
  await page.getByRole("button", { name: "Research MSFT", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "MSFT research", exact: true });
  await expect(dialog).toBeVisible();
  await dialog.getByRole("button", { name: "Chart", exact: true }).click();
  await expect(dialog.locator("canvas").first()).toBeVisible();
  await dialog.getByRole("button", { name: "Financials", exact: true }).click();
  await expect(dialog.getByRole("columnheader", { name: "Revenue", exact: true })).toBeVisible();
  await dialog.getByRole("button", { name: "Events", exact: true }).click();
  await expect(dialog.getByRole("heading", { name: "MSFT earnings" })).toBeVisible();
  await dialog.getByRole("button", { name: "Write note", exact: true }).click();
  await expect(dialog.getByLabel("Journal symbol")).toHaveValue("MSFT");
  await dialog.getByLabel("Entry title").fill("Research workflow evidence");
  await dialog.getByLabel("Entry notes").fill("Linked from the watchlist");
  await dialog.getByRole("button", { name: "Chart", exact: true }).click();
  await dialog.getByRole("button", { name: "Notes", exact: true }).click();
  await expect(dialog.getByLabel("Entry title")).toHaveValue("Research workflow evidence");
  await page.screenshot({ path: testInfo.outputPath("desktop-research.png") });
  await dialog.getByRole("button", { name: "Save entry", exact: true }).click();
  await expect(dialog.getByRole("button", { name: "MSFT · Research workflow evidence", exact: true })).toBeVisible();
  await dialog.getByRole("button", { name: "Create alert", exact: true }).click();
  await expect(dialog.getByLabel("Alert symbol")).toHaveValue("MSFT");
  await dialog.getByLabel("Alert threshold").fill("99999");
  await dialog.locator("form").getByRole("button", { name: "Create alert", exact: true }).click();
  await expect(dialog.getByText(/Alert saved\./)).toBeVisible();
  await page.keyboard.press("Escape"); await expect(dialog).toBeHidden();
  await expect(page.getByRole("button", { name: "Research MSFT", exact: true }).last()).toBeFocused();
});
test("mobile navigation and command search preserve the desktop layout", async ({ page }, testInfo) => {
  await signIn(page); await blank(page, "Mobile layout");
  await page.getByRole("button", { name: /^CHART/ }).click();
  const desktop = await page.evaluate(() => JSON.parse(localStorage.getItem("openterminal-workspace")!).state);
  await page.setViewportSize({ width: 390, height: 844 });
  const nav = page.getByRole("navigation", { name: "Mobile navigation" });
  await expect(nav).toBeVisible();
  await page.reload();
  await expect(page.getByRole("heading", { name: "Holdings", exact: true })).toBeVisible();
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem("openterminal-workspace")!).state)).toEqual(desktop);
  await nav.getByRole("button", { name: "Holdings", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Holdings", exact: true })).toBeVisible();
  await nav.getByRole("button", { name: "Alerts", exact: true }).click();
  await expect(page.getByLabel("Alert symbol")).toBeVisible();
  await nav.getByRole("button", { name: "Events", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Holdings events", exact: true })).toBeVisible();
  await expect(page.getByRole("cell", { name: /Fixture CPI/ })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("mobile-events.png") });
  await nav.getByRole("button", { name: "Workspace", exact: true }).click();
  await expect(page.locator(".react-grid-layout")).toHaveCount(0);
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem("openterminal-workspace")!).state)).toEqual(desktop);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole("button", { name: "Research AAPL", exact: true }).first().click();
  const research = page.getByRole("dialog", { name: "AAPL research", exact: true });
  await expect(research.getByText("Fixture Company", { exact: true })).toBeVisible();
  const bounds = await research.boundingBox();
  expect(bounds?.width).toBe(390); expect(bounds?.height).toBe(844);
  await page.screenshot({ path: testInfo.outputPath("mobile-research.png") });
  await research.getByRole("button", { name: "Close research", exact: true }).click();
  await nav.getByRole("button", { name: "Tools", exact: true }).click();
  await page.getByLabel("Filter widgets").fill("sync");
  await page.getByRole("button", { name: "DEVICE SYNC", exact: true }).click();
  await expect(page.getByText("Server snapshot:", { exact: false })).toBeVisible();
  await page.getByRole("button", { name: /search symbols, features/ }).click();
  await page.getByRole("combobox", { name: "Search symbols, features and workspaces" }).fill("> backup");
  await page.keyboard.press("Enter");
  await expect(page.getByLabel("Actions for Backup / Restore", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: /search symbols, features/ }).click();
  await page.getByRole("combobox", { name: "Search symbols, features and workspaces" }).fill("@ My workspace");
  await page.keyboard.press("Enter");
  await expect(page.locator("#workspace-select option:checked")).toHaveText("My workspace");
  await page.setViewportSize({ width: 1600, height: 1100 });
  await expect(page.locator(".react-grid-layout")).toBeVisible();
});
