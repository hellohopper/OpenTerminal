import { test, expect } from "@playwright/test";
import { signIn } from "./helpers";
test("fresh phone sessions use simple navigation and remain readable at narrow widths", async ({ page }, info) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await signIn(page);
  const notices = page.getByRole("button", { name: /^Dismiss alert event / });
  while (await notices.count()) await notices.first().click();
  await expect(page.getByLabel("Interface mode", { exact: true })).toHaveValue("simple");
  const nav = page.getByRole("navigation", { name: "Mobile simple navigation", exact: true });
  await expect(nav).toBeVisible();
  await nav.getByRole("button", { name: "Watchlist", exact: true }).click();
  await expect(page.getByRole("button", { name: "Research MSFT", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Install app", exact: true }).click();
  await expect(page.getByRole("dialog", { name: "Install OpenTerminal", exact: true })).toContainText("Add to Home Screen");
  await page.getByRole("button", { name: "Done", exact: true }).click();
  await page.screenshot({ path: info.outputPath("simple-phone.png") });
  await page.getByRole("button", { name: "UI settings", exact: true }).click();
  await page.getByRole("dialog", { name: "UI settings", exact: true }).getByRole("button", { name: "20px", exact: true }).click();
  await page.getByLabel("Language / 语言", { exact: true }).selectOption("zh");
  await page.getByRole("button", { name: "完成", exact: true }).click();
  await page.setViewportSize({ width: 320, height: 740 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await expect(page.getByRole("navigation", { name: "手机简单版导航", exact: true })).toBeInViewport();
});
test("installs a public offline fallback without caching authenticated pages or API responses", async ({ page, context }) => {
  await signIn(page);
  await page.evaluate(async () => { await navigator.serviceWorker.ready; if (!navigator.serviceWorker.controller) await new Promise<void>(resolve => navigator.serviceWorker.addEventListener("controllerchange", () => resolve(), { once: true })); });
  const manifest = await (await page.request.get("/manifest.webmanifest")).json();
  expect(manifest.display).toBe("standalone"); expect(manifest.icons).toHaveLength(3);
  for (const icon of manifest.icons) expect((await page.request.get(icon.src)).ok()).toBe(true);
  await context.setOffline(true);
  await expect(page.getByRole("status").filter({ hasText: "You are offline" })).toBeVisible();
  await page.reload();
  await expect(page.getByRole("heading", { name: "You are offline · 当前离线", exact: true })).toBeVisible();
  await context.setOffline(false); await page.getByRole("button", { name: "Try again · 重试", exact: true }).click();
  await expect(page.getByLabel("Interface mode", { exact: true })).toBeVisible();
  const cached = await page.evaluate(async () => (await Promise.all((await caches.keys()).map(async name => (await (await caches.open(name)).keys()).map(r => new URL(r.url).pathname)))).flat());
  expect(cached.sort()).toEqual(["/app-icon-192.png", "/offline.html"]);
});
